import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { selectPartnerOffer, affiliateOffersConfigured } from "../lib/partner-offers";

const config = { repairUrl: "https://partner.example/second-opinion", replacementUrl: "https://partner.example/replace" };
assert.equal(selectPartnerOffer("repair", false, config)?.kind, "repair");
assert.equal(selectPartnerOffer("close", false, config)?.kind, "repair");
assert.equal(selectPartnerOffer("replace", false, config)?.kind, "replacement");
assert.equal(selectPartnerOffer("safety", false, config), null);
assert.equal(selectPartnerOffer("repair", true, config), null);
assert.equal(selectPartnerOffer("replace", true, config), null);
assert.equal(selectPartnerOffer("repair", false, {}), null);
assert.equal(selectPartnerOffer("replace", false, {}), null);
assert.equal(selectPartnerOffer("repair", false, { repairUrl: "http://partner.example/offer" }), null);
assert.equal(selectPartnerOffer("repair", false, { repairUrl: "javascript:alert(1)" }), null);
assert.equal(selectPartnerOffer("repair", false, { repairUrl: "https://user:pass@partner.example/path" }), null);
assert.equal(selectPartnerOffer("repair", false, { repairUrl: "https://localhost/path" }), null);
assert.equal(selectPartnerOffer("repair", false, { repairUrl: "https://partner.example:8443/path" }), null);
assert.equal(affiliateOffersConfigured(), false, "no affiliate offer should be active without configured partner URLs");
const markup = readFileSync("components/PartnerOffer.tsx", "utf8");
assert.ok(markup.includes('rel="sponsored noopener noreferrer"'));
assert.ok(markup.includes('analyticsEvents.affiliateCtaClicked'));
assert.ok(markup.includes('analyticsEvents.affiliateOfferViewed'));
assert.ok(markup.includes('IntersectionObserver'));
assert.ok(markup.includes('if (!offer) return null'));
const resultsMarkup = readFileSync("components/ResultsClient.tsx", "utf8");
assert.ok(resultsMarkup.includes('safetyFlag={result.safetyFlag}'));
const redirects = readFileSync("next.config.ts", "utf8");
assert.ok(redirects.includes('source: "/guides/is-a-5000-car-repair-worth-it"'));
assert.ok(redirects.includes('destination: "/guides/is-a-5000-dollar-car-repair-worth-it"'));
console.log("Affiliate release contracts passed.");
